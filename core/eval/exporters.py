"""Optional eval harness exporters.

These exporters generate config/code snippets for external eval frameworks
without making Promptfoo, DeepEval, or Inspect AI runtime dependencies.
"""

from __future__ import annotations

import json
from typing import Literal

from core.eval.outcome_runner import SMOKE_FIXTURES

EvalHarness = Literal["promptfoo", "deepeval", "inspect", "all"]


def _yaml_scalar(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("'", "''")
    return f"'{escaped}'"


def promptfoo_config() -> str:
    """Return a Promptfoo config for local Elite smoke fixtures."""
    lines = [
        "# Generated by elite-reasoning-mcp. Requires: npm install -g promptfoo",
        "description: Elite Reasoning MCP-on/off smoke eval",
        "prompts:",
        "  - '{{task}}'",
        "providers:",
        "  - id: openai:gpt-4.1-mini",
        "    label: baseline",
        "  - id: openai:gpt-4.1-mini",
        "    label: elite_mcp_guided",
        "tests:",
    ]
    for fixture in SMOKE_FIXTURES:
        lines.extend(
            [
                "  - vars:",
                f"      task: {_yaml_scalar(fixture.prompt)}",
                "    assert:",
                "      - type: contains-any",
                "        value:",
                "          - validation",
                "          - evidence",
                "          - confidence",
                "          - test",
                "      - type: javascript",
                "        value: output.length > 80",
            ]
        )
    return "\n".join(lines) + "\n"


