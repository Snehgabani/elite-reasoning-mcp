def export_eval_harness(harness: EvalHarness = "all") -> dict[str, str]:
    """Return requested eval harness files as a mapping of path to content."""
    normalized = (harness or "all").lower()
    files: dict[str, str] = {}
    if normalized in {"promptfoo", "all"}:
        files["evals/promptfooconfig.yaml"] = promptfoo_config()
    if normalized in {"deepeval", "all"}:
        files["tests/evals/test_elite_reasoning.py"] = deepeval_test_file()
    if normalized in {"inspect", "all"}:
        files["evals/elite_reasoning.py"] = inspect_eval_file()
    if not files:
        raise ValueError("harness must be one of: promptfoo, deepeval, inspect, all")
    return files


def eval_harness_markdown(harness: EvalHarness = "all") -> str:
    """Render harness files as Markdown."""
    files = export_eval_harness(harness)
    lines = [
        "# Elite Eval Harness Export",
        "",
        "These files are generated snippets. External frameworks stay optional.",
        "",
    ]
    for path, content in files.items():
        language = "yaml" if path.endswith((".yaml", ".yml")) else "python"
        lines.extend([f"## `{path}`", f"```{language}", content.rstrip(), "```", ""])
    return "\n".join(lines).rstrip()
