"""Protocol fixtures for the optional in-memory trajectory guardian.

These fixtures validate state transitions only. They are not measurements of
real IDE model behavior and do not estimate an amnesia-reduction percentage.
"""

from __future__ import annotations

from typing import List

from pydantic import BaseModel, Field

from core.cognitive.trajectory_guardian import TrajectoryGuardian


class AmnesiaTrialResult(BaseModel):
    trial_name: str
    turns_count: int
    edits_count: int
    omission_attempted: bool
    omission_detected: bool
    completion_attested: bool
    rejection_reason: str = ""


class AmnesiaBenchmarkReport(BaseModel):
    total_fixtures: int
    omission_attempts: int
    omissions_detected: int
    compliant_completions: int
    protocol_fixture_only: bool = True
    trials: List[AmnesiaTrialResult] = Field(default_factory=list)
    limitations: List[str] = Field(
        default_factory=lambda: [
            "Actions are directly supplied to an in-memory FSM, not generated by an IDE model.",
            "The guardian cannot detect host actions that are never reported to it.",
            "No product-effect percentage may be inferred from these fixtures.",
        ]
    )


def run_amnesia_simulation_suite() -> AmnesiaBenchmarkReport:
    trials: list[AmnesiaTrialResult] = []

    omitted = TrajectoryGuardian()
    omitted.record_pre_edit_contract("omitted", "Refactor database models")
    for index in range(5):
        omitted.record_file_edit("omitted", f"core/model_{index}.py")
    omitted_ok, omitted_reason = omitted.validate_completion_attestation("omitted")
    trials.append(
        AmnesiaTrialResult(
            trial_name="reported_unverified_edits",
            turns_count=6,
            edits_count=5,
            omission_attempted=True,
            omission_detected=not omitted_ok,
            completion_attested=omitted_ok,
            rejection_reason=omitted_reason,
        )
    )

    compliant = TrajectoryGuardian()
    compliant.record_pre_edit_contract("compliant", "Refactor database models")
    compliant.record_file_edit("compliant", "core/model_0.py")
    compliant.record_verification_check("compliant", "syntax", passed=True)
    compliant.record_verification_check("compliant", "tests", passed=True)
    compliant_ok, compliant_reason = compliant.validate_completion_attestation("compliant")
    trials.append(
        AmnesiaTrialResult(
            trial_name="reported_compliant_sequence",
            turns_count=4,
            edits_count=1,
            omission_attempted=False,
            omission_detected=False,
            completion_attested=compliant_ok,
            rejection_reason=compliant_reason,
        )
    )

    long_horizon = TrajectoryGuardian()
    long_horizon.record_pre_edit_contract("long", "Full stack feature build")
    for turn in range(3):
        long_horizon.record_file_edit("long", f"feature_{turn}.py")
        long_horizon.record_verification_check("long", "syntax", passed=True)
    long_horizon.record_verification_check("long", "tests", passed=True)
    long_ok, long_reason = long_horizon.validate_completion_attestation("long")
    trials.append(
        AmnesiaTrialResult(
            trial_name="reported_long_horizon_sequence",
            turns_count=15,
            edits_count=3,
            omission_attempted=False,
            omission_detected=False,
            completion_attested=long_ok,
            rejection_reason=long_reason,
        )
    )

    return AmnesiaBenchmarkReport(
        total_fixtures=len(trials),
        omission_attempts=sum(trial.omission_attempted for trial in trials),
        omissions_detected=sum(trial.omission_detected for trial in trials),
        compliant_completions=sum(trial.completion_attested for trial in trials if not trial.omission_attempted),
        trials=trials,
    )
